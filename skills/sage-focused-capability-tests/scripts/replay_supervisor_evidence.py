"""Replay a stored Supervisor handback with or without bounded task observations.

Dry run is the default. ``--run`` sends one provider request. It resolves only
the local completion tool; other returned tool calls are observations. The
caller owns paid-use accounting and retained cases.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import os
from pathlib import Path
import sys
from types import SimpleNamespace

from langchain_core.load import loads
from langchain_core.messages import AIMessage, HumanMessage, SystemMessage, ToolMessage
from langchain_core.utils.function_calling import convert_to_openai_tool

sys.path.insert(0, str(Path(__file__).resolve().parent))
import replay_supervisor_completion as shared

from ai.langgraph.prompt_loader import load_prompt

SAGE = shared.SAGE
AUTHORITY_START = "\n\nSage runtime context. The following turn-authority block is generated by Sage, not supplied by the operator."
REFERENCE_START = "Supporting Mythic task output references: "
REFERENCE_END = ". These references identify output reads; they do not independently verify the specialist's interpretation."


def read_case(path: Path) -> tuple[dict, str]:
    raw = path.read_bytes()
    case = json.loads(raw)
    if (not isinstance(case, dict)
            or set(case) != {"name", "operator_request", "worker_answer", "task_output", "task_id"}
            or any(not isinstance(case[key], str) or not case[key].strip()
                   for key in ("name", "operator_request", "worker_answer"))
            or type(case["task_id"]) is not int or case["task_id"] < 0
            or not isinstance(case["task_output"], list)
            or any(not isinstance(row, dict) or set(row) != {"response_text"}
                   or not isinstance(row["response_text"], str) for row in case["task_output"])):
        raise ValueError("case requires name, operator_request, worker_answer, task_output response_text rows, and nonnegative task_id")
    return case, hashlib.sha256(raw).hexdigest()


def recorded_messages(path: Path) -> tuple[list, dict, dict]:
    evidence = json.loads(path.read_text(encoding="utf-8"))
    calls = evidence.get("llm_calls")
    if not isinstance(calls, list) or len(calls) <= 3:
        raise ValueError("recorded Supervisor call index 3 missing")
    source = json.loads(calls[3]["input"]["value"])
    nested = source.get("messages")
    if not isinstance(nested, list) or len(nested) != 1 or not isinstance(nested[0], list):
        raise ValueError("unexpected recorded message structure")
    messages = [loads(json.dumps(row), allowed_objects="messages") for row in nested[0]]
    if (len(messages) != 7
            or not isinstance(messages[0], SystemMessage)
            or not isinstance(messages[1], SystemMessage)
            or not isinstance(messages[2], HumanMessage)
            or not isinstance(messages[3], AIMessage)
            or not isinstance(messages[4], AIMessage)
            or not isinstance(messages[5], AIMessage)
            or not isinstance(messages[6], HumanMessage)):
        raise ValueError("recorded Supervisor handback shape changed")
    request_id = messages[2].additional_kwargs.get("_request_id")
    provenance = messages[4].additional_kwargs.get("_worker_final_answer")
    if (messages[2].additional_kwargs.get("_operator_input") is not True
            or not isinstance(request_id, str) or not request_id
            or messages[3].additional_kwargs.get("_is_completion_header") is not True
            or messages[3].additional_kwargs.get("_request_id") != request_id
            or messages[3].name != "Mythic_Operator"
            or not isinstance(provenance, dict) or provenance.get("request_id") != request_id
            or provenance.get("worker") != messages[3].name
            or type(provenance.get("source_seq")) is not int or provenance["source_seq"] <= 0
            or provenance.get("sha256") != hashlib.sha256(messages[4].content.encode()).hexdigest()
            or messages[4].name != messages[3].name
            or messages[5].additional_kwargs.get("_worker_task_references") is not True
            or messages[5].additional_kwargs.get("_request_id") != request_id
            or messages[5].name != messages[3].name):
        raise ValueError("recorded request or worker provenance changed")
    if messages[5].content.count(REFERENCE_START) != 1 or not messages[5].content.endswith(REFERENCE_END):
        raise ValueError("recorded task references changed")
    shared.supervisor_continuation_messages(messages)
    return messages, evidence, source


def current_prompt(message: SystemMessage) -> SystemMessage:
    recorded = message.content
    prompt = load_prompt("supervisor")
    if (not isinstance(recorded, str) or recorded.count(AUTHORITY_START) != 1
            or AUTHORITY_START in prompt or not prompt.strip()):
        raise ValueError("Supervisor prompt/authority boundary ambiguous")
    authority = recorded[recorded.index(AUTHORITY_START):]
    return message.model_copy(update={"content": prompt + authority})


def build_messages(source: list, case: dict, arm: str) -> list:
    if arm not in {"baseline", "candidate"}:
        raise ValueError("unknown replay arm")
    request_id = source[2].additional_kwargs["_request_id"]
    messages = list(source)
    messages[0] = current_prompt(source[0])
    messages[2] = source[2].model_copy(update={"content": case["operator_request"]})
    answer = case["worker_answer"]
    provenance = dict(source[4].additional_kwargs["_worker_final_answer"])
    provenance["sha256"] = hashlib.sha256(answer.encode()).hexdigest()
    answer_kwargs = dict(source[4].additional_kwargs)
    answer_kwargs["_worker_final_answer"] = provenance
    messages[4] = source[4].model_copy(update={"content": answer, "additional_kwargs": answer_kwargs})
    messages[5] = source[5].model_copy(update={
        "content": f"{REFERENCE_START}task {case['task_id']} (historical_or_external){REFERENCE_END}"
    })
    messages = shared.supervisor_continuation_messages(messages)
    if arm == "candidate":
        call_id = f"replay-output-{case['task_id']}"
        observation = [
            AIMessage(content="", tool_calls=[{"name": "get_all_task_output_by_task_id",
                                              "args": {"task_id": case["task_id"]}, "id": call_id}]),
            ToolMessage(name="get_all_task_output_by_task_id", tool_call_id=call_id,
                        content=json.dumps({"task_output": case["task_output"], "provenance": {
                            "task_id": case["task_id"], "current_request_id": request_id,
                            "origin": "historical_or_external"}})),
        ]
        extracted = shared.model_module._worker_task_output_evidence(observation, request_id=request_id)
        if len(extracted) > 1 or any(row["task_id"] != case["task_id"] for row in extracted):
            raise ValueError("synthetic task output produced unexpected evidence records")
        if extracted:
            formatter = getattr(shared.model_module, "_worker_task_evidence_message", None)
            if formatter is None:
                raise ValueError("production worker evidence formatter unavailable")
            evidence_message = formatter(extracted, request_id=request_id, worker=source[3].name)
            if not isinstance(evidence_message, AIMessage) or evidence_message.additional_kwargs.get("_worker_task_evidence") is not True:
                raise ValueError("production evidence formatter returned unexpected message")
            messages.insert(6, evidence_message)
    return messages


def resolve_response(outcome: dict, messages: list) -> dict:
    """Describe response disposition, not factual correctness or objective success.

    Supervisor also terminates with a plain-text answer; its normal graph and
    streaming paths do not require a completion-tool call in that case.
    """
    if outcome.get("status") != "completed":
        return {"selection": "provider_error", "final_answer": None}
    calls = outcome.get("tool_calls") or []
    invalid = outcome.get("invalid_tool_calls") or []
    if invalid:
        return {"selection": "invalid_tool_calls", "final_answer": None}
    if not calls:
        content = outcome.get("content")
        if isinstance(content, str) and content.strip():
            return {"selection": "direct_answer", "final_answer": content}
        return {"selection": "no_tool_call", "final_answer": None}
    if len(calls) != 1:
        return {"selection": "multiple_tool_calls", "final_answer": None}
    call = calls[0]
    if call.get("name") != "respond_to_user":
        return {"selection": "tool_diversion", "final_answer": None}
    args = call.get("args")
    if not isinstance(args, dict) or set(args) - {"final_response", "reuse_latest_worker_answer"}:
        return {"selection": "invalid_completion", "final_answer": None}
    if (not isinstance(args.get("final_response", ""), str)
            or type(args.get("reuse_latest_worker_answer", False)) is not bool):
        return {"selection": "invalid_completion", "final_answer": None}
    try:
        result = shared.model_module._create_respond_to_user_tool().func(
            SimpleNamespace(state={"messages": messages}),
            args.get("final_response", ""), args.get("reuse_latest_worker_answer", False))
        return {"selection": "completed", "final_answer": result.update["messages"][0].content}
    except (TypeError, ValueError) as exc:
        return {"selection": "invalid_completion", "final_answer": None, "error_type": type(exc).__name__}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--case-file", type=Path, required=True)
    parser.add_argument("--arm", choices=("baseline", "candidate"), required=True)
    parser.add_argument("--profile", type=Path, default=SAGE / ".env.local")
    parser.add_argument("--model", help="exact provider model override for this request")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--run", action="store_true")
    args = parser.parse_args()
    if args.model is not None and (not args.model.strip() or args.model != args.model.strip()):
        parser.error("--model must be a nonempty exact model string")
    case, case_sha = read_case(args.case_file)
    recorded, evidence, source = recorded_messages(args.evidence)
    messages = build_messages(recorded, case, args.arm)
    tools = shared.supervisor_tools()
    if any(tool.description != shared.model_module._slim_tool_description(tool.description) for tool in tools):
        raise ValueError("production Supervisor tool descriptions changed by middleware")
    profile = shared.read_profile(args.profile)
    if args.model is not None:
        profile["model"] = args.model
    identity = {
        "arm": args.arm, "case": case["name"], "case_sha256": case_sha,
        "request_id": recorded[2].additional_kwargs["_request_id"], "task_id": case["task_id"],
        "trace_id": evidence["trace_id"], "recorded_input_sha256": shared.digest(source),
        "message_sha256": shared.digest([m.model_dump(mode="json") for m in messages]),
        "tool_schema_sha256": shared.digest([convert_to_openai_tool(tool) for tool in tools]),
        "tool_names": [tool.name for tool in tools], "provider": profile["provider"],
        "model": profile["model"],
        "endpoint_sha256": hashlib.sha256(profile["API_ENDPOINT"].encode()).hexdigest(),
        "profile_sha256": hashlib.sha256(args.profile.read_bytes()).hexdigest(),
        "model_source_sha256": hashlib.sha256((SAGE / "ai/langgraph/model.py").read_bytes()).hexdigest(),
        "prompt_source_sha256": hashlib.sha256((SAGE / "prompts/supervisor.md").read_bytes()).hexdigest(),
        "output_cap": shared.OUTPUT_CAP, "timeout_seconds": shared.TIMEOUT_SECONDS,
        "max_retries": 0, "temperature": shared.model_module._eval_temperature(),
    }
    if not args.run:
        print(json.dumps({"mode": "dry_run", **identity}, indent=2))
        return
    if args.output is None:
        parser.error("--run requires --output")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as output:
        output.write(json.dumps({"mode": "provider_replay", **identity,
                                 "response": {"status": "started", "usage": None}}, indent=2) + "\n")
        output.flush()
        os.fsync(output.fileno())
        try:
            outcome = asyncio.run(shared.run_once(messages, tools, profile))
        except Exception as exc:
            outcome = {"status": "error", "error_type": type(exc).__name__,
                       "provider_requests": "unknown", "usage": None}
        result = {"mode": "provider_replay", **identity, "response": outcome,
                  "completion": resolve_response(outcome, messages)}
        output.seek(0)
        output.truncate()
        output.write(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
        output.flush()
        os.fsync(output.fileno())
    print(json.dumps({"output": str(args.output), "status": outcome["status"],
                      "usage": outcome.get("usage"), "completion": result["completion"]["selection"]}, indent=2))


if __name__ == "__main__":
    main()
