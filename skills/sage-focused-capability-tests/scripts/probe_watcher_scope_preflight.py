#!/usr/bin/env python3
"""Offline: run every GraphQL document a Sage Watcher scan sends through Mythic's own API-token preflight.

Mythic servers built from the Mythic-v4.0.0 branch at d8a94943 or later check each HTTP GraphQL request from an API
token before Hasura runs it (`authorization.Authorize`): the token needs the read scope of every table the selection
crosses. A Watcher token is issued with Sage's `REQUIRED_WATCHER_SCOPES`; Mythic stores those plus the scopes they
imply. This probe asks Mythic's own code, offline, whether that token may send each document Sage's Watcher modules
define, the way AWS's policy simulator or a Kubernetes SelfSubjectAccessReview asks before acting.

  probe_watcher_scope_preflight.py [--drop-scope SCOPE ...] [--sage-root DIR] [--mythic-dir DIR] [--keep-scratch]

It exports the documents from Sage's modules (the Watcher bot's whoami, owner-channel and active-Watcher reads, every
operation-memory stream page, the findings channel read/create and message, and the mythic package's event-log
mutation). It copies the Mythic Go module (`<mythic>/mythic-docker/src`, without `files/` and the server binary) to a
scratch directory, adds a test file there and runs `go test` offline (GOPROXY=off). Nothing in the Mythic checkout
changes and no Mythic server is contacted. Mythic computes the effective scopes from the requested ones with its own
scope catalog (`Includes`, as `CreateAPIToken` does) and the report says whether they equal Sage's
`REQUIRED_WATCHER_EFFECTIVE_SCOPES`.

The Mythic checkout is the directory of MYTHIC_CLI unless --mythic-dir names one. --drop-scope removes a requested
scope before the closure (to see which documents a token without it could not send). Output is one JSON report; exit 0
when every document is allowed and the closures agree, 1 otherwise, 2 when the probe cannot run.
"""

from __future__ import annotations

import argparse
import inspect
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SAGE_ROOT = REPO_ROOT / "Payload_Type" / "sage"

# Symbolic identifiers for the value lookups Mythic's model rules make (channel type by id). The owner channel is
# the locked Watcher's AI channel; the findings channel is the managed standard channel.
OPERATION_ID = 1
OWNER_CHANNEL_ID = 8
FINDINGS_CHANNEL_ID = 9
LOOKUP_FACTS = {str(OWNER_CHANNEL_ID): "ai", str(FINDINGS_CHANNEL_ID): "standard"}
_SKIP_COPY = {"files", "mythic_server"}
_TEST_FILE = "zz_sage_watcher_scope_preflight_test.go"
_RESULT_PREFIX = "SAGEPROBE "

GO_TEST = r'''package authorization

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"testing"
)

// Generated by Sage's probe_watcher_scope_preflight.py in a scratch copy; never part of Mythic.
func TestSageWatcherScopePreflight(t *testing.T) {
	raw, err := os.ReadFile(os.Getenv("SAGE_PROBE_INPUT"))
	if err != nil {
		t.Fatal(err)
	}
	var input struct {
		Requested   []string          `json:"requested_scopes"`
		OperationID int               `json:"operation_id"`
		Facts       map[string]string `json:"lookup_facts"`
		Documents   []struct {
			Name      string                 `json:"name"`
			Query     string                 `json:"query"`
			Variables map[string]interface{} `json:"variables"`
		} `json:"documents"`
	}
	if err := json.Unmarshal(raw, &input); err != nil {
		t.Fatal(err)
	}
	definitions := map[string]ScopeDefinition{}
	for _, definition := range ScopeDefinitions() {
		definitions[definition.Name] = definition
	}
	// The closure CreateAPIToken stores: every requested scope and, once each, the scopes it includes.
	granted := map[string]bool{}
	pending := []string{}
	for _, scope := range input.Requested {
		if _, known := definitions[scope]; !known {
			t.Fatalf("unknown requested scope %q", scope)
		}
		if !granted[scope] {
			granted[scope] = true
			pending = append(pending, scope)
		}
	}
	for i := 0; i < len(pending); i++ {
		for _, included := range definitions[pending[i]].Includes {
			if !granted[included] {
				granted[included] = true
				pending = append(pending, included)
			}
		}
	}
	effective := []string{}
	for scope := range granted {
		effective = append(effective, scope)
	}
	sort.Strings(effective)
	line, _ := json.Marshal(map[string]interface{}{"effective_scopes": effective})
	fmt.Println("SAGEPROBE " + string(line))
	principal := Principal{APITokenID: 1, OperationID: input.OperationID, Scopes: granted}
	resolve := func(lookup ValueLookup, id interface{}) (string, error) {
		if fact, ok := input.Facts[fmt.Sprint(id)]; ok {
			return fact, nil
		}
		return "", fmt.Errorf("no lookup fact for %s id %v", lookup.Column, id)
	}
	for _, document := range input.Documents {
		request := GraphQLRequest{Query: document.Query, Variables: document.Variables}
		result := map[string]interface{}{"name": document.Name, "allowed": true, "reason": ""}
		if err := request.Authorize(Current, principal, resolve); err != nil {
			result["allowed"], result["reason"] = false, err.Error()
		}
		line, _ := json.Marshal(result)
		fmt.Println("SAGEPROBE " + string(line))
	}
}
'''


class ProbeUnavailable(RuntimeError):
    """The probe cannot run here (configuration or toolchain); it says which."""


def _eventlog_document(mythic_module: Any) -> str:
    source = inspect.getsource(mythic_module.send_event_log_message)
    match = re.search(r'query\s*=\s*"""(?P<query>.*?)"""', source, re.DOTALL)
    if match is None:
        raise ProbeUnavailable("could not read the event-log mutation from the mythic package")
    return match.group("query")


def export_documents(sage_root: Path) -> dict[str, Any]:
    """Every GraphQL document a Watcher scan sends, from Sage's own modules, and the scope constants."""
    sys.path.insert(0, str(sage_root))
    from mythic import mythic as mythic_module

    from sage_chat import mythic_findings_delivery as delivery
    from sage_chat import operation_memory_source as source
    from sage_chat import watcher_control as control

    page = {"op": OPERATION_ID, "after_ts": "1970-01-01T00:00:00Z", "after_id": 0, "limit": 2}
    documents = [
        ("whoami", delivery._WHOAMI_QUERY, {}),
        ("owner_channel", control._CHANNEL_QUERY, {"channel_id": OWNER_CHANNEL_ID, "operation_id": OPERATION_ID}),
        ("active_watchers", control._ACTIVE_WATCHERS_QUERY, {"operation_id": OPERATION_ID}),
    ]
    documents += [(f"memory_{key}", source._QUERIES[key], dict(page)) for key in source.STREAM_KEYS]
    documents += [
        ("findings_channel", delivery._FINDINGS_CHANNEL_QUERY, {"name": delivery.FINDINGS_CHANNEL_NAME}),
        ("create_findings_channel", delivery._CREATE_FINDINGS_CHANNEL,
         {"name": delivery.FINDINGS_CHANNEL_NAME, "description": delivery.FINDINGS_CHANNEL_DESCRIPTION}),
        ("create_findings_message", delivery._CREATE_FINDINGS_MESSAGE,
         {"channelId": FINDINGS_CHANNEL_ID, "message": "probe"}),
        ("eventlog", _eventlog_document(mythic_module),
         {"level": "info", "message": delivery.GENERIC_MYTHIC_NOTICE, "source": "sage-findings-watcher",
          "warning": True}),
    ]
    return {
        "requested_scopes": sorted(delivery.REQUIRED_WATCHER_SCOPES),
        "sage_effective_scopes": sorted(delivery.REQUIRED_WATCHER_EFFECTIVE_SCOPES),
        "documents": [{"name": name, "query": query, "variables": variables}
                      for name, query, variables in documents],
    }


def mythic_dir(explicit: str | None) -> Path:
    if explicit:
        directory = Path(explicit)
    else:
        cli = os.environ.get("MYTHIC_CLI", "").strip()
        if not cli:
            raise ProbeUnavailable("MYTHIC_CLI is not set (or pass --mythic-dir)")
        directory = Path(cli).parent
    if not (directory / "mythic-docker" / "src" / "authorization" / "graphql.go").is_file():
        raise ProbeUnavailable(f"{directory} has no mythic-docker/src/authorization/graphql.go")
    return directory


def _head(directory: Path) -> str:
    completed = subprocess.run(["git", "-C", str(directory), "rev-parse", "HEAD"], capture_output=True, text=True,
                               timeout=60)
    return completed.stdout.strip()[:12]


def run_authorizer(mythic: Path, probe_input: dict[str, Any], *, keep_scratch: bool = False) -> dict[str, Any]:
    """Mythic's own `Authorize` over the documents, in a scratch copy of its Go module."""
    if shutil.which("go") is None:
        raise ProbeUnavailable("go is not on PATH")
    scratch = Path(tempfile.mkdtemp(prefix="sage-watcher-preflight-"))
    try:
        module = scratch / "src"
        shutil.copytree(mythic / "mythic-docker" / "src", module,
                        ignore=lambda directory, names: [n for n in names
                                                         if n in _SKIP_COPY and Path(directory).name == "src"])
        (module / "authorization" / _TEST_FILE).write_text(GO_TEST)
        input_path = scratch / "input.json"
        input_path.write_text(json.dumps(probe_input))
        env = {**os.environ, "SAGE_PROBE_INPUT": str(input_path), "GOFLAGS": "-mod=mod", "GOPROXY": "off",
               "GOWORK": "off"}
        completed = subprocess.run(
            ["go", "test", "./authorization/", "-run", "^TestSageWatcherScopePreflight$", "-count=1", "-v"],
            cwd=module, env=env, capture_output=True, text=True, timeout=600)
        rows = [json.loads(line[len(_RESULT_PREFIX):]) for line in completed.stdout.splitlines()
                if line.startswith(_RESULT_PREFIX)]
        if completed.returncode != 0 or not rows:
            tail = (completed.stdout + completed.stderr).strip().splitlines()[-15:]
            raise ProbeUnavailable("go test did not run the probe: " + " | ".join(tail))
        return {"effective_scopes": rows[0]["effective_scopes"], "documents": rows[1:],
                **({"scratch": str(scratch)} if keep_scratch else {})}
    finally:
        if not keep_scratch:
            shutil.rmtree(scratch, ignore_errors=True)


def report(exported: dict[str, Any], requested: list[str], authorized: dict[str, Any], head: str) -> dict[str, Any]:
    documents = authorized["documents"]
    denied = [row for row in documents if not row["allowed"]]
    closure_matches = sorted(authorized["effective_scopes"]) == sorted(exported["sage_effective_scopes"])
    expected = {row["name"] for row in exported["documents"]}
    complete = {row["name"] for row in documents} == expected
    return {
        "mythic_head": head,
        "requested_scopes": requested,
        "mythic_effective_scopes": authorized["effective_scopes"],
        "sage_effective_scopes": exported["sage_effective_scopes"],
        "closure_matches_sage": closure_matches,
        "documents": documents,
        "every_document_reported": complete,
        "verdict": "allowed" if (complete and not denied and closure_matches) else "denied",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--drop-scope", action="append", default=[],
                        help="remove this scope from the requested set before Mythic's closure (repeatable)")
    parser.add_argument("--sage-root", default=str(DEFAULT_SAGE_ROOT),
                        help="the Payload_Type/sage directory whose modules define the documents")
    parser.add_argument("--mythic-dir", help="Mythic checkout (default: the directory of MYTHIC_CLI)")
    parser.add_argument("--keep-scratch", action="store_true", help="keep the scratch Go module and print its path")
    args = parser.parse_args(argv)
    try:
        mythic = mythic_dir(args.mythic_dir)
        exported = export_documents(Path(args.sage_root))
        requested = [scope for scope in exported["requested_scopes"] if scope not in set(args.drop_scope)]
        probe_input = {"requested_scopes": requested, "operation_id": OPERATION_ID, "lookup_facts": LOOKUP_FACTS,
                       "documents": exported["documents"]}
        authorized = run_authorizer(mythic, probe_input, keep_scratch=args.keep_scratch)
    except ProbeUnavailable as error:
        print(json.dumps({"verdict": "did_not_run", "error": str(error)}, indent=1))
        return 2
    result = report(exported, requested, authorized, _head(mythic))
    if args.keep_scratch:
        result["scratch"] = authorized["scratch"]
    print(json.dumps(result, indent=1))
    return 0 if result["verdict"] == "allowed" else 1


if __name__ == "__main__":
    sys.exit(main())
